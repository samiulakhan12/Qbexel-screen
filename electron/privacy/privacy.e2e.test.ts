// The real pipeline on a synthetic recording: ffmpeg samples the frames, tesseract.js
// reads them, the patterns find the email and the API key drawn into the video, and the
// accepted finding becomes a blur on the document.
//
// Opt-in, because it needs ffmpeg, the tesseract language model and a few seconds:
//
//   QBEXEL_PRIVACY_E2E=1 QBEXEL_OCR_CACHE=/path/with/eng.traineddata \
//     npx vitest run electron/privacy/privacy.e2e.test.ts
//
// ffmpeg is the app's (`resolveFfmpeg`) when the box has it, else the first one on PATH;
// the scan itself takes the path as an argument and never looks for one.
//
// Without the cache the model is downloaded once (about 5 MB). The video is generated by
// the test itself with ffmpeg's drawtext, so nothing but ffmpeg and fonts is needed.

import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import {
	type AxcutDocument,
	createEmptyDocument,
	documentSchema,
} from "../../src/lib/ai-edition/schema";
import { resolveFfmpeg } from "../media/audioPeaks";
import { applyPrivacyFindings } from "./apply";
import { scanDocumentForSensitiveContent, scanVideoFileForSensitiveContent } from "./scan";

const enabled = process.env.QBEXEL_PRIVACY_E2E === "1";
const ffmpeg =
	resolveFfmpeg() ?? (spawnSync("which", ["ffmpeg"]).stdout?.toString().trim() || null);
const FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf";

function drawtext(text: string, y: number, enable?: string): string {
	const escaped = text.replace(/:/g, "\\:").replace(/'/g, "\\'");
	return `drawtext=fontfile=${FONT}:text='${escaped}':fontsize=40:fontcolor=black:x=80:y=${y}${enable ? `:enable='${enable}'` : ""}`;
}

describe.skipIf(!enabled || !ffmpeg)("Privacy Guardian end to end", () => {
	let dir = "";
	let video = "";
	const cachePath = process.env.QBEXEL_OCR_CACHE ?? path.join(tmpdir(), "qbexel-ocr-cache");

	beforeAll(() => {
		dir = mkdtempSync(path.join(tmpdir(), "qbexel-privacy-e2e-"));
		video = path.join(dir, "sample.mp4");
		const filters = [
			drawtext("Welcome to the billing settings", 120),
			drawtext("Contact jane.doe@example.com for help", 300),
			drawtext("API key sk-live-4f9a8b7c6d5e4f3a2b1c0d9e8f7a6b5c", 460, "between(t,2,6)"),
		].join(",");
		const result = spawnSync(
			ffmpeg as string,
			[
				"-y",
				"-loglevel",
				"error",
				"-f",
				"lavfi",
				"-i",
				"color=c=white:s=1280x720:d=6:r=30",
				"-vf",
				filters,
				"-c:v",
				"libx264",
				"-pix_fmt",
				"yuv420p",
				"-t",
				"6",
				video,
			],
			{ encoding: "utf8" },
		);
		if (result.status !== 0) throw new Error(`ffmpeg failed: ${result.stderr}`);
	}, 60_000);

	afterAll(() => {
		rmSync(dir, { recursive: true, force: true });
	});

	function fixture(): AxcutDocument {
		const base = createEmptyDocument({ projectId: "p", title: "Billing tour" });
		return documentSchema.parse({
			...base,
			assets: [
				{
					id: "asset_1",
					kind: "video",
					label: "sample",
					originalPath: video,
					durationSec: 6,
					video: { codec: "h264", width: 1280, height: 720, fps: 30 },
					cameraTrack: null,
				},
			],
			project: { ...base.project, primaryAssetId: "asset_1" },
			timeline: {
				...base.timeline,
				clips: [
					{
						id: "clip_1",
						assetId: "asset_1",
						sourceStartSec: 0,
						sourceEndSec: 6,
						timelineStartSec: 0,
						timelineEndSec: 6,
						wordRefs: [],
						origin: "user",
						reason: "",
					},
				],
			},
		});
	}

	it("finds the email and the key on screen, and blurs them through the agent tools", async () => {
		const document = fixture();
		const scan = await scanDocumentForSensitiveContent(document, {
			ocr: { cachePath },
			sampleEveryMs: 1000,
			ffmpegPath: ffmpeg,
		});
		// Said first so a failure names its cause (a missing ffmpeg, an OCR start error).
		expect(scan.warnings).toEqual([]);
		expect(scan.ocrAvailable).toBe(true);
		expect(scan.framesScanned).toBeGreaterThanOrEqual(5);
		const kinds = scan.findings.map((f) => f.kind).sort();
		expect(kinds).toEqual(["api-key", "email"]);
		const email = scan.findings.find((f) => f.kind === "email");
		const key = scan.findings.find((f) => f.kind === "api-key");
		expect(email?.preview).toBe("j••••••e@example.com");
		expect(key?.preview.startsWith("sk-")).toBe(true);
		expect(key?.preview).not.toContain("4f9a8b7c");
		// The email shows for the whole clip, the key only from 2 s.
		expect(email?.boxes.length).toBeGreaterThanOrEqual(5);
		expect(Math.min(...(key?.boxes.map((b) => b.timeMs) ?? [0]))).toBeGreaterThanOrEqual(2000);
		// Boxes land where the text was drawn: x from 80 px of 1280, y near 300 / 720.
		const box = email?.boxes[0];
		expect(box?.x).toBeGreaterThan(0.05);
		expect(box?.x).toBeLessThan(0.3);
		expect(box?.y).toBeGreaterThan(0.35);
		expect(box?.y).toBeLessThan(0.45);

		const withScan: AxcutDocument = {
			...document,
			privacy: { version: 1, scan, reviewedAt: null, reviewedClipSignature: null },
		};
		const applied = applyPrivacyFindings(
			withScan,
			scan.findings.map((f) => f.id),
		);
		expect(applied.failed).toEqual([]);
		expect(applied.applied.length).toBe(2);
		expect(applied.document.annotations.every((a) => a.type === "blur")).toBe(true);
		expect(applied.document.annotations.length).toBeGreaterThanOrEqual(2);
	}, 180_000);

	it("checks a finished video file the same way", async () => {
		const result = await scanVideoFileForSensitiveContent(video, {
			ocr: { cachePath },
			durationSec: 6,
			sampleEveryMs: 1000,
			ffmpegPath: ffmpeg,
		});
		expect(result.findings.map((f) => f.kind).sort()).toEqual(["api-key", "email"]);
	}, 120_000);
});
